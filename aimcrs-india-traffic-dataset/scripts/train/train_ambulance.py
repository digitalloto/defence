import os
import sys
import json
import shutil
import random
from pathlib import Path
from datetime import datetime

PROJECT_ROOT = Path(__file__).resolve().parent.parent.parent
sys.path.insert(0, str(PROJECT_ROOT))

try:
    from loguru import logger
except ImportError:
    print("ERROR: loguru is not installed. Fix: pip install loguru")
    sys.exit(1)

# ----- PATHS -----
DATASETS_DIR = PROJECT_ROOT / "datasets"
TRAIN_DIR = DATASETS_DIR / "train"
VAL_DIR = DATASETS_DIR / "validation"
TEST_DIR = DATASETS_DIR / "test"
MODELS_DIR = PROJECT_ROOT / "models" / "ambulance_detection"
LABELLED_DIR = PROJECT_ROOT / "processed" / "labelled"
AUGMENTED_DIR = PROJECT_ROOT / "processed" / "augmented"
LOGS_DIR = PROJECT_ROOT / "logs"

# ----- TRAINING SETTINGS -----
# These control how the AI learns.

# How many times the AI looks at the entire dataset.
# More epochs = better learning, but takes longer.
EPOCHS = 100

# How many images the AI looks at at once.
# Bigger = faster training but needs more memory (RAM/GPU).
# Start with 16. If you get "out of memory" errors, try 8.
BATCH_SIZE = 16

# Image size for training (must match our processed images)
IMAGE_SIZE = 640

# Train/Validation/Test split ratios
TRAIN_RATIO = 0.8   # 80% for training
VAL_RATIO = 0.1     # 10% for validation (checking during training)
TEST_RATIO = 0.1    # 10% for final testing

# Ambulance class ID in our labelling system
AMBULANCE_CLASS_ID = 5


def setup_logging():
    """Set up logging."""
    LOGS_DIR.mkdir(parents=True, exist_ok=True)
    logger.add(
        str(LOGS_DIR / "train_ambulance.log"),
        rotation="10 MB",
        retention="30 days",
        level="INFO",
        format="{time:YYYY-MM-DD HH:mm:ss} | {level} | {message}",
    )
    logger.info("=" * 60)
    logger.info("Ambulance Detection Training Started")
    logger.info("=" * 60)


def collect_ambulance_images():
    """
    Find all images that contain ambulances.
    These are the most valuable images in our entire dataset.
    """
    logger.info("Collecting ambulance images...")
    ambulance_images = []
    all_images = []

    # Search through labelled and augmented directories
    search_dirs = [LABELLED_DIR, AUGMENTED_DIR]

    for search_dir in search_dirs:
        if not search_dir.exists():
            continue

        for img_path in search_dir.rglob("*.jpg"):
            label_path = img_path.with_suffix(".txt")
            if not label_path.exists():
                continue

            # Check if any label is ambulance (class 5)
            with open(label_path, "r") as f:
                lines = f.readlines()

            has_ambulance = False
            for line in lines:
                parts = line.strip().split()
                if parts and int(parts[0]) == AMBULANCE_CLASS_ID:
                    has_ambulance = True
                    break

            if has_ambulance:
                ambulance_images.append(img_path)
            all_images.append(img_path)

    logger.info(
        f"Found {len(ambulance_images)} ambulance images "
        f"out of {len(all_images)} total"
    )
    return ambulance_images, all_images


def create_dataset_yaml(output_path):
    """
    Create the YAML configuration file that YOLO needs for training.

    This file tells YOLO:
    - Where to find training images
    - Where to find validation images
    - What classes (vehicle types) exist
    """
    yaml_content = f"""# AIMCRS Ambulance Detection Dataset
# Auto-generated by train_ambulance.py

# Paths (relative to this file)
train: {TRAIN_DIR / 'images'}
val: {VAL_DIR / 'images'}
test: {TEST_DIR / 'images'}

# Number of classes
nc: 9

# Class names (must match label IDs)
names:
  0: car
  1: motorcycle
  2: auto_rickshaw
  3: bus
  4: truck
  5: ambulance
  6: pedestrian
  7: cycle
  8: animal
"""
    output_path.parent.mkdir(parents=True, exist_ok=True)
    with open(output_path, "w") as f:
        f.write(yaml_content)

    logger.info(f"Dataset YAML created: {output_path}")
    return output_path


def split_dataset(all_images):
    """
    Split images into train/validation/test sets.

    What does this mean?
    - Training set (80%): AI learns from these
    - Validation set (10%): AI checks itself during learning
    - Test set (10%): We test the final AI on these
      (it never sees these during training — fair test)
    """
    random.shuffle(all_images)
    total = len(all_images)

    train_end = int(total * TRAIN_RATIO)
    val_end = int(total * (TRAIN_RATIO + VAL_RATIO))

    train_images = all_images[:train_end]
    val_images = all_images[train_end:val_end]
    test_images = all_images[val_end:]

    logger.info(
        f"Split: {len(train_images)} train, "
        f"{len(val_images)} val, {len(test_images)} test"
    )

    return train_images, val_images, test_images


def copy_to_split(images, dest_dir):
    """
    Copy images and their labels to train/val/test folders.
    YOLO expects this structure:
      split_dir/
        images/   ← image files go here
        labels/   ← label files go here
    """
    img_dir = dest_dir / "images"
    lbl_dir = dest_dir / "labels"
    img_dir.mkdir(parents=True, exist_ok=True)
    lbl_dir.mkdir(parents=True, exist_ok=True)

    copied = 0
    for img_path in images:
        # Copy image
        dest_img = img_dir / img_path.name
        shutil.copy2(img_path, dest_img)

        # Copy label file if it exists
        label_path = img_path.with_suffix(".txt")
        if label_path.exists():
            dest_label = lbl_dir / label_path.name
            shutil.copy2(label_path, dest_label)

        copied += 1

    return copied


def train_model(yaml_path):
    """
    Train YOLOv8 on our ambulance dataset.

    What happens during training:
    1. YOLO looks at all training images
    2. It tries to detect vehicles
    3. It checks its answers against our labels
    4. It adjusts itself to be more accurate
    5. Repeat for EPOCHS rounds
    6. After each round, it checks against validation set

    The best model (highest accuracy) is saved automatically.
    """
    try:
        from ultralytics import YOLO
    except ImportError:
        print("ERROR: ultralytics not installed. Fix: pip install ultralytics")
        return None

    print("\n  Starting training...")
    print(f"  Epochs: {EPOCHS}")
    print(f"  Batch size: {BATCH_SIZE}")
    print(f"  Image size: {IMAGE_SIZE}")
    print(f"  This may take a while (hours on CPU, minutes on GPU)")
    print()

    # Start with pre-trained YOLOv8 nano model
    # Then fine-tune it on our specific Indian traffic data
    model = YOLO("yolov8n.pt")

    logger.info("Starting YOLO training...")

    results = model.train(
        data=str(yaml_path),
        epochs=EPOCHS,
        batch=BATCH_SIZE,
        imgsz=IMAGE_SIZE,
        name="aimcrs_ambulance",
        project=str(MODELS_DIR),
        exist_ok=True,
        # Save the best model automatically
        save=True,
        # Show progress
        verbose=True,
        # Use all available CPU cores (or GPU if available)
        workers=4,
    )

    logger.info("Training complete!")
    return results


def evaluate_model():
    """
    Test the trained model and show accuracy scores.
    """
    try:
        from ultralytics import YOLO
    except ImportError:
        return

    # Find the best model weights
    best_weights = MODELS_DIR / "aimcrs_ambulance" / "weights" / "best.pt"

    if not best_weights.exists():
        print("  No trained model found yet.")
        return

    print("\n  Evaluating model on test set...")
    model = YOLO(str(best_weights))

    # Run evaluation
    results = model.val(
        data=str(DATASETS_DIR / "dataset.yaml"),
        split="test",
    )

    # Print results
    print("\n  Model Evaluation Results:")
    print(f"    mAP50 (accuracy at 50% overlap): {results.box.map50:.3f}")
    print(f"    mAP50-95 (strict accuracy): {results.box.map:.3f}")

    # Save results
    eval_results = {
        "model": "aimcrs_ambulance_yolov8n",
        "mAP50": float(results.box.map50),
        "mAP50_95": float(results.box.map),
        "evaluated_at": datetime.now().isoformat(),
    }

    results_path = MODELS_DIR / "evaluation_results.json"
    with open(results_path, "w") as f:
        json.dump(eval_results, f, indent=2)

    logger.info(f"Evaluation: mAP50={results.box.map50:.3f}")
    return eval_results


def main():
    """
    Main function — full ambulance detection training pipeline.

    Steps:
    1. Collect all labelled images
    2. Split into train/val/test
    3. Create dataset config
    4. Train YOLOv8
    5. Evaluate results
    """
    print("=" * 50)
    print("  AIMCRS Ambulance Detection Training")
    print("  Training YOLOv8 for Indian ambulance detection")
    print("=" * 50)

    setup_logging()

    # Step 1: Collect images
    print("\n--- Step 1: Collecting images ---")
    ambulance_images, all_images = collect_ambulance_images()
    print(f"  Ambulance images: {len(ambulance_images)}")
    print(f"  Total images: {len(all_images)}")

    if not all_images:
        print("\n  No labelled images found!")
        print("  Run these steps first:")
        print("  1. python scripts/process/process_pipeline.py")
        print("  2. python scripts/label/auto_label.py")
        return

    # Step 2: Split dataset
    print("\n--- Step 2: Splitting dataset ---")
    train_imgs, val_imgs, test_imgs = split_dataset(all_images)
    print(f"  Training: {len(train_imgs)} images")
    print(f"  Validation: {len(val_imgs)} images")
    print(f"  Test: {len(test_imgs)} images")

    # Copy to split directories
    print("\n--- Step 3: Preparing dataset folders ---")
    t = copy_to_split(train_imgs, TRAIN_DIR)
    v = copy_to_split(val_imgs, VAL_DIR)
    e = copy_to_split(test_imgs, TEST_DIR)
    print(f"  Copied: {t} train, {v} val, {e} test")

    # Step 3: Create YAML config
    yaml_path = create_dataset_yaml(DATASETS_DIR / "dataset.yaml")

    # Step 4: Train
    print("\n--- Step 4: Training model ---")
    train_model(yaml_path)

    # Step 5: Evaluate
    print("\n--- Step 5: Evaluating model ---")
    evaluate_model()

    print("\n" + "=" * 50)
    print("  Training Complete!")
    print("=" * 50)
    print(f"  Model saved to: {MODELS_DIR}")
    print(f"  Next: python scripts/train/train_flow.py")

    logger.info("Ambulance Detection Training Pipeline Complete")


if __name__ == "__main__":
    main()
