#!/usr/bin/env python3
# ============================================
# AIMCRS — Replit Setup Helper
# ============================================
# Run this ONCE when you first set up on Replit.
# It installs everything and checks your API keys.
#
# How to run: python aimcrs-india-traffic-dataset/setup_replit.py
# ============================================

import os
import sys
import subprocess
from pathlib import Path

# Find project root
SCRIPT_DIR = Path(__file__).resolve().parent
PROJECT_ROOT = SCRIPT_DIR

print("=" * 50)
print("  AIMCRS — Replit Setup")
print("  Setting up your environment")
print("=" * 50)
print()

# ----- STEP 1: Install Python packages -----
print("STEP 1: Installing Python packages...")
print("  (This takes 2-3 minutes, be patient)")
print()

requirements = PROJECT_ROOT / "requirements.txt"
if requirements.exists():
    result = subprocess.run(
        [sys.executable, "-m", "pip", "install", "-r", str(requirements)],
        capture_output=True,
        text=True,
    )
    if result.returncode == 0:
        print("  DONE — All packages installed!")
    else:
        print("  WARNING — Some packages may have failed:")
        # Show just the errors, not all the download noise
        for line in result.stderr.split("\n"):
            if "ERROR" in line or "error" in line:
                print(f"    {line}")
        print("  Don't worry — most scripts will still work.")
else:
    print("  ERROR — requirements.txt not found!")
    print(f"  Expected at: {requirements}")

print()

# ----- STEP 2: Create .env file from secrets -----
print("STEP 2: Setting up API keys from Replit Secrets...")

# On Replit, secrets are automatically available as
# environment variables. We create a .env file from them
# so our scripts can also read them with python-dotenv.

env_path = PROJECT_ROOT / ".env"

# List of all API keys we use
api_keys = {
    "GOOGLE_API_KEY": os.environ.get("GOOGLE_API_KEY", ""),
    "KAGGLE_USERNAME": os.environ.get("KAGGLE_USERNAME", ""),
    "KAGGLE_KEY": os.environ.get("KAGGLE_KEY", ""),
    "ROBOFLOW_API_KEY": os.environ.get("ROBOFLOW_API_KEY", ""),
    "DATA_GOV_IN_API_KEY": os.environ.get("DATA_GOV_IN_API_KEY", ""),
    "TOMTOM_API_KEY": os.environ.get("TOMTOM_API_KEY", ""),
    "HERE_API_KEY": os.environ.get("HERE_API_KEY", ""),
    "MAPPLS_CLIENT_ID": os.environ.get("MAPPLS_CLIENT_ID", ""),
    "MAPPLS_CLIENT_SECRET": os.environ.get("MAPPLS_CLIENT_SECRET", ""),
}

with open(env_path, "w") as f:
    f.write("# Auto-generated from Replit Secrets\n")
    f.write("# Do NOT edit this file — edit Secrets instead\n\n")
    for key, value in api_keys.items():
        f.write(f"{key}={value}\n")
    f.write("\nMAX_CONCURRENT_DOWNLOADS=2\n")
    f.write("DOWNLOAD_DELAY_SECONDS=5\n")
    f.write("LOG_DIR=logs\n")

print("  DONE — .env file created from your Secrets")
print()

# ----- STEP 3: Check which keys are set -----
print("STEP 3: Checking your API keys...")
print()

found = 0
missing = 0

for key, value in api_keys.items():
    if value and value not in ("", "your_google_api_key_here"):
        print(f"  OK    {key}")
        found += 1
    else:
        print(f"  EMPTY {key} — add it in Replit Secrets (lock icon)")
        missing += 1

print()
print(f"  Keys found: {found}")
print(f"  Keys missing: {missing}")

if missing > 0:
    print()
    print("  Don't worry! You can add keys later.")
    print("  Scripts will skip sources where keys are missing.")
    print("  The YouTube downloader needs NO keys — start there!")

print()

# ----- STEP 4: Create folders -----
print("STEP 4: Creating data folders...")

folders = [
    "raw/youtube", "raw/government", "raw/academic", "raw/kaggle",
    "processed/labelled", "processed/unlabelled", "processed/augmented",
    "models/vehicle_detection", "models/ambulance_detection",
    "models/flow_analysis",
    "datasets/train", "datasets/validation", "datasets/test",
    "logs",
]

for folder in folders:
    (PROJECT_ROOT / folder).mkdir(parents=True, exist_ok=True)

print("  DONE — All folders ready")
print()

# ----- STEP 5: Summary -----
print("=" * 50)
print("  SETUP COMPLETE!")
print("=" * 50)
print()
print("  What to do next:")
print()
print("  OPTION A — Run the dashboard (see your stats):")
print("    Click the green 'Run' button at the top")
print("    Or type in Shell:")
print("    cd aimcrs-india-traffic-dataset && python scripts/dashboard.py")
print()
print("  OPTION B — Start downloading data:")
print("    Type in Shell:")
print("    cd aimcrs-india-traffic-dataset")
print("    python scripts/download/youtube_downloader.py")
print()
print("  OPTION C — Run everything in order:")
print("    cd aimcrs-india-traffic-dataset")
print("    python scripts/download/youtube_downloader.py")
print("    python scripts/download/government_downloader.py")
print("    python scripts/download/academic_downloader.py")
print("    python scripts/download/kaggle_downloader.py")
print("    python scripts/download/roboflow_downloader.py")
print("    python scripts/download/live_feeds.py")
print("    python scripts/process/process_pipeline.py")
print("    python scripts/label/auto_label.py")
print("    python scripts/process/augment.py")
print("    python scripts/train/train_ambulance.py")
print("    python scripts/train/train_flow.py")
print("    python scripts/train/viltics_comparison.py")
print("    python scripts/dashboard.py")
print()
print("=" * 50)
